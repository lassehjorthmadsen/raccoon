"""Drive the real GNU Backgammon binary as a decision oracle.

The ``gnubg-nn`` Python package (:mod:`raccoon.eval.gnubg_adapter`) is the right
tool for everything cubeless, and it is what every Raccoon number before exp026
was measured against. It **cannot play a cubeful money game**: its
``evaluate_cube_decision`` raises ``RuntimeError: Not implemented for money`` —
the binding covers match play only — and it ranks checker plays on cubeless
equity, so it has no opinion about a live cube on either half of a turn.

The installed ``gnubg`` binary does both, with its real cubeful engine: cube
decisions come out of a search that decides the cube at every node, not out of a
closed form applied once at the root. This module talks to it.

**We stay in charge of the game.** GNUBG is asked "given this position, this cube
and these dice, what do you do?" and nothing else. It never runs the session, so
Raccoon keeps rolling the dice — which is what preserves the variance-reduced
estimator in :mod:`raccoon.eval.luck`, since that needs to intercept every
pre-roll state.

**Positions go in by name, not by field order.** GNUBG also accepts a FIBS
``board:`` line over a socket, which is one colon-separated string of ~50
unlabelled integers; guessing that layout produced self-contradictory cube
answers (a position it doubled when told the doubler may not double) and every
reachable copy of the FIBS specification is truncated. Here every piece of state
is set by a named command instead — ``set board`` with GNUBG's own Position ID,
then ``set turn`` / ``set dice`` / ``set cube value`` / ``set cube owner`` — so
there is no field order to get wrong. It is also marginally faster: ~71 ms per
2-ply decision against ~84 ms for the socket.

The Position ID is generated by ``gnubg_nn.position_id``, i.e. by GNUBG's own
encoder, so the board half of the contract cannot drift between the package and
the binary. :func:`GnubgCli.echo_position_id` proves that at run time by asking
GNUBG what position it thinks it is holding: the ID it echoes back must be the
one we sent. That check is **exact and independent of the evaluator**, which
matters because of the next paragraph.

**The binary and the package are NOT the same evaluator.** They ship different
weights — Debian's ``/usr/lib/gnubg/gnubg.wd`` is a 408 KB binary file, while
``gnubg_nn`` carries a 1.1 MB text ``gnubg.weights`` — and their ply-0
probabilities differ by one or two units in the third decimal on real positions.
Ply 0 has no search, so that difference is the nets themselves, not a harness
bug. Two consequences worth carrying forward:

* An exact-agreement check between the two is not available, so
  :func:`GnubgCli.cubeless_probs` is for *comparison*, with a tolerance, and the
  exact control is the Position ID round trip above.
* Every Raccoon number before exp026 — the distillation teacher, the BGSage
  benchmark's GNUBG rows, exp019/exp020's ppg — was measured against the
  **package's** nets. A result against the binary is a result against a
  different, and more current, GNU Backgammon. Say which one a number refers to.

Robustness notes, learned the hard way:

* GNUBG **segfaults on malformed input**, so :class:`GnubgCli` treats a dead
  process as expected and restarts it rather than propagating a broken pipe into
  the middle of a 7,000-game run.
* Replies have no prompt to synchronise on. Every command batch is followed by a
  deliberate nonsense keyword, and output is read until GNUBG echoes it back —
  ``Unknown keyword `...'.`` is deterministic and cannot appear in a legitimate
  answer.
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass

DEFAULT_EXE = "/usr/games/gnubg"

# A keyword GNUBG cannot possibly understand, used to mark the end of a reply.
_SENTINEL = "raccoonsync"
_SENTINEL_LINE = f"Unknown keyword `{_SENTINEL}'."

# "    1. Cubeful 2-ply    24/22 13/8        Eq.: +0.178"
_MOVE_RE = re.compile(
    r"^\s*(\d+)\.\s+\S+\s+(\d+)-ply\s+(.+?)\s\s+Eq\.:\s*([+-]?[\d.]+)"
)
# "1. No double           +0.105"
_CUBE_RE = re.compile(
    r"^\s*(\d)\.\s+(No double|Double, pass|Double, take)\s+([+-]?[\d.]+)"
)
# " 2 ply: 0.525   0.149   0.007   0.125   0.005   +0.076    +0.105" and, for
# ply 0, "static: 0.521 ..." -- GNUBG labels the raw net evaluation by name
# rather than as "0 ply".
_EVAL_RE = re.compile(
    r"^\s*(static|\d+\s*ply):\s+" + r"\s+".join([r"([\d.]+)"] * 5)
    + r"\s+([+-][\d.]+)"
)

# GNUBG spells "the cube is in the middle" as owner `both` -- neither `centre`,
# `center`, `none` nor `middle` is accepted, they all fall through to
# "You must specify which player owns the cube".
CENTRE = "both"


@dataclass(frozen=True)
class GnubgCubeAnalysis:
    """GNUBG's three cubeful money equities, from the player on roll's POV.

    Same shape and sign convention as
    :class:`raccoon.cube.janowski.CubeEquities`, so the two are directly
    comparable — which is what lets exp026 score our closed form against GNUBG's
    cubeful *search* on any position, the comparison ``docs/cube.qmd`` lists as
    open.
    """

    nd: float           # no double, play on
    dt: float           # double, opponent takes
    dp: float           # double, opponent passes (1.0 at cube value 1)
    action: str         # GNUBG's own "Proper cube action" line, verbatim

    @property
    def should_double(self) -> bool:
        return min(self.dt, self.dp) > self.nd

    @property
    def should_take(self) -> bool:
        return self.dt < self.dp


class GnubgProtocolError(RuntimeError):
    """GNUBG answered something this module cannot parse."""


class GnubgCli:
    """A persistent ``gnubg`` subprocess answering one position at a time.

    ``ply`` is the evaluation depth for both checker play and cube decisions —
    GNUBG's own numbering, matching :mod:`raccoon.eval.gnubg_adapter`. ``jacoby``
    defaults to False, which is Raccoon's target game (``goal.md``).

    ``use_cube=False`` turns the cube off entirely, so GNUBG ranks checker plays
    on **cubeless** equity. That is not a playing mode Raccoon wants, but it is
    the right setting for isolating one evaluator against another: it strips the
    cube model out of the comparison and leaves only the nets.
    """

    def __init__(self, ply: int = 2, jacoby: bool = False,
                 use_cube: bool = True, exe: str = DEFAULT_EXE) -> None:
        self.ply = ply
        self.jacoby = jacoby
        self.use_cube = use_cube
        self.exe = exe
        self._proc: subprocess.Popen | None = None
        self.restarts = 0
        self._start()

    # --- process lifecycle ---------------------------------------------------

    def _setup_commands(self) -> list[str]:
        return [
            "set matchlength 0",                      # money game
            f"set jacoby {'on' if self.jacoby else 'off'}",
            f"set cube use {'on' if self.use_cube else 'off'}",
            "set automatic game off",
            "set confirm new off",
            "set confirm save off",
            f"set evaluation chequer eval plies {self.ply}",
            f"set evaluation cubedecision eval plies {self.ply}",
            f"set analysis chequerplay eval plies {self.ply}",
            f"set analysis cubedecision eval plies {self.ply}",
            "new game",
        ]

    def _start(self) -> None:
        self._proc = subprocess.Popen(
            [self.exe, "-t", "-q"],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, text=True, bufsize=1,
            env={**os.environ, "TERM": "dumb"},
        )
        self._exchange(self._setup_commands())

    def close(self) -> None:
        if self._proc is None:
            return
        try:
            self._proc.stdin.write("quit\n")
            self._proc.stdin.flush()
            self._proc.wait(timeout=5)
        except Exception:
            self._proc.kill()
        finally:
            self._proc = None

    def __enter__(self) -> "GnubgCli":
        return self

    def __exit__(self, *exc) -> None:
        self.close()

    # --- the wire ------------------------------------------------------------

    def _exchange(self, commands: list[str]) -> list[str]:
        """Send ``commands``, return every output line up to the sentinel echo.

        Restarts GNUBG once and retries if the process has died — it segfaults on
        malformed input, and a 7,000-game run must not end because one position
        upset it.
        """
        try:
            return self._exchange_once(commands)
        except (BrokenPipeError, GnubgProtocolError, ValueError):
            self.restarts += 1
            try:
                if self._proc is not None:
                    self._proc.kill()
            except Exception:
                pass
            self._proc = None
            self._start()
            return self._exchange_once(commands)

    def _exchange_once(self, commands: list[str]) -> list[str]:
        proc = self._proc
        if proc is None or proc.poll() is not None:
            raise BrokenPipeError("gnubg is not running")
        for cmd in commands:
            proc.stdin.write(cmd + "\n")
        proc.stdin.write(_SENTINEL + "\n")
        proc.stdin.flush()

        lines: list[str] = []
        while True:
            line = proc.stdout.readline()
            if not line:
                raise BrokenPipeError("gnubg closed its output")
            line = line.rstrip("\n")
            if line.strip() == _SENTINEL_LINE:
                return lines
            lines.append(line)

    # --- positions -----------------------------------------------------------

    @staticmethod
    def position_id(board: list[list[int]]) -> str:
        """GNUBG Position ID for a :func:`~raccoon.eval.gnubg_adapter.board_from_view`
        board, produced by GNUBG's own encoder via ``gnubg_nn``."""
        import gnubg_nn

        return gnubg_nn.position_id(board)

    def _position_commands(self, board, cube_value: int, cube_owner: str,
                           dice: tuple[int, int] | None) -> list[str]:
        """Set board, cube and dice, with the side to move as GNUBG's player 1.

        ``board`` is ``[slot0, slot1]`` with **slot 1 on roll**, the layout
        ``board_from_view`` produces and the one ``gnubg_nn`` encodes. ``turn 1``
        therefore names the player the Position ID is written from.
        ``cube_owner`` is ``"centre"``, ``"0"`` or ``"1"`` in the same seating.
        """
        cmds = [
            f"set board {self.position_id(board)}",
            "set turn 1",
            f"set cube value {cube_value}",
            f"set cube owner {cube_owner}",
        ]
        if dice is not None:
            cmds.append(f"set dice {dice[0]} {dice[1]}")
        return cmds

    # --- what we actually ask it ---------------------------------------------

    def echo_position_id(self, board, cube_value: int = 1,
                         cube_owner: str = CENTRE) -> str:
        """The Position ID GNUBG reports back after we set this board.

        The exact harness-correctness control. It compares an encoding against
        itself rather than one evaluator against another, so it stays valid
        despite the binary and the package shipping different weights, and a
        perspective or seating bug shows up as a mismatched ID rather than as a
        plausible-looking equity.
        """
        out = self._exchange(
            self._position_commands(board, cube_value, cube_owner, None)
            + ["show board"]
        )
        for line in out:
            if "Position ID" in line:
                return line.split(":", 1)[1].strip()
        raise GnubgProtocolError(f"no Position ID in show board output: {out!r}")

    def cubeless_probs(self, board, cube_value: int = 1,
                       cube_owner: str = CENTRE) -> tuple[float, ...]:
        """GNUBG's cumulative 5-vector at ``self.ply``, from the mover's POV.

        Rounded to three decimals, which is all GNUBG prints. Comparable to
        ``gnubg_nn.probabilities(board, ply)`` but **not equal to it** — the two
        ship different weights (see the module docstring), and on real positions
        they differ by a unit or two in that last digit. Use
        :func:`echo_position_id` for the exact encoding check.
        """
        out = self._exchange(
            self._position_commands(board, cube_value, cube_owner, None) + ["eval"]
        )
        best = None
        for line in out:
            m = _EVAL_RE.match(line)
            if not m:
                continue
            label = m.group(1)
            row_ply = 0 if label == "static" else int(label.split()[0])
            if row_ply == self.ply:
                best = tuple(float(m.group(i)) for i in range(2, 7))
        if best is None:
            raise GnubgProtocolError(
                f"no {self.ply}-ply row in eval output: {out!r}"
            )
        return best

    def best_move(self, board, dice: tuple[int, int], cube_value: int = 1,
                  cube_owner: str = CENTRE) -> str:
        """GNUBG's chosen play, in its own notation (e.g. ``"8/5 6/5"``).

        Returns ``""`` when the roll has no legal play (a dance), which GNUBG
        reports by offering no candidates.
        """
        out = self._exchange(
            self._position_commands(board, cube_value, cube_owner, dice) + ["hint"]
        )
        for line in out:
            m = _MOVE_RE.match(line)
            if m and m.group(1) == "1":
                return m.group(3).strip()
        joined = " ".join(out).lower()
        if "no legal move" in joined or "cannot move" in joined or "dance" in joined:
            return ""
        raise GnubgProtocolError(f"no ranked move in hint output: {out!r}")

    def cube_analysis(self, board, cube_value: int = 1,
                      cube_owner: str = CENTRE) -> GnubgCubeAnalysis:
        """GNUBG's cubeful money cube decision for the player on roll.

        The position must be pre-roll (no dice), and the mover must be allowed to
        double — i.e. the cube is centred or owned by them.
        """
        out = self._exchange(
            self._position_commands(board, cube_value, cube_owner, None) + ["hint"]
        )
        found: dict[str, float] = {}
        action = ""
        for line in out:
            m = _CUBE_RE.match(line)
            if m:
                found[m.group(2)] = float(m.group(3))
            elif "Proper cube action" in line:
                action = line.split(":", 1)[1].strip()
        try:
            return GnubgCubeAnalysis(
                nd=found["No double"], dt=found["Double, take"],
                dp=found["Double, pass"], action=action,
            )
        except KeyError as e:
            raise GnubgProtocolError(
                f"cube analysis missing {e} in: {out!r}"
            ) from e


# --- turning GNUBG's answer back into a move -----------------------------------
#
# GNUBG answers in its own notation, which has four shapes that all appear in
# real play:
#
#     8/5 6/5        two separate checkers
#     24/13          one checker chained through both dice (24->18->13)
#     13/3(2)        two checkers making the same play
#     bar/20*        entering, with a hit
#     13/off         bearing off
#
# Rather than trust a parse, we turn the notation into a **target board** and then
# require that board to appear among the mover's legal turn outcomes. A parser bug
# then fails loudly on the next position instead of quietly playing a different
# move for thousands of games -- which is the failure this project can least
# afford to ship into a strength measurement.

_HOP_RE = re.compile(r"^(bar|\d+)((?:/\d+\*?)*)(/off)?(\(\d+\))?$", re.IGNORECASE)

BAR = 25
OFF = 0


def parse_move(notation: str) -> list[tuple[int, int]]:
    """GNUBG move notation -> ``[(from, to), ...]`` hops in the mover's numbering.

    ``bar`` is 25 and ``off`` is 0. A chained play expands into one hop per die
    (``24/18/13`` -> ``[(24, 18), (18, 13)]``) because an intermediate point can
    be where a hit happens. A ``(n)`` multiplier repeats the whole group.
    Hit markers are parsed but ignored: whether a hop hits is a property of the
    board, and reading it off the board rather than off the text means the two
    can never disagree.
    """
    hops: list[tuple[int, int]] = []
    for token in notation.split():
        m = _HOP_RE.match(token.strip())
        if not m:
            raise GnubgProtocolError(f"cannot parse move token {token!r} in {notation!r}")
        head, middle, off, mult = m.groups()
        stops = [BAR if head.lower() == "bar" else int(head)]
        for part in re.findall(r"/(\d+)\*?", middle or ""):
            stops.append(int(part))
        if off:
            stops.append(OFF)
        if len(stops) < 2:
            raise GnubgProtocolError(f"move token {token!r} has no destination")
        group = [(stops[i], stops[i + 1]) for i in range(len(stops) - 1)]
        hops.extend(group * (int(mult[1:-1]) if mult else 1))
    return hops


def apply_move(board: list[list[int]], hops: list[tuple[int, int]]) -> list[list[int]]:
    """Apply ``hops`` to a ``board_from_view`` board, returning a new board.

    ``board`` is ``[opponent, mover]`` with the mover on roll, each side's points
    stored from its own POV and index 24 the bar. A hit is detected from the
    board -- the mover landing on a point where the opponent has exactly one
    checker -- rather than from the notation's ``*``.
    """
    opp, me = list(board[0]), list(board[1])
    for src, dst in hops:
        me[24 if src == BAR else src - 1] -= 1
        if me[24 if src == BAR else src - 1] < 0:
            raise GnubgProtocolError(f"move takes a checker from empty point {src}")
        if dst != OFF:
            # Our point `dst` is the opponent's point `25 - dst`.
            opp_idx = 25 - dst - 1
            if opp[opp_idx] == 1:
                opp[opp_idx] = 0
                opp[24] += 1
            elif opp[opp_idx] > 1:
                raise GnubgProtocolError(f"move lands on a point held by {opp[opp_idx]}")
            me[dst - 1] += 1
    return [opp, me]


def target_board(board: list[list[int]], notation: str) -> list[list[int]]:
    """The board GNUBG's ``notation`` reaches from ``board``, mover still slot 1."""
    return apply_move(board, parse_move(notation))


def resting_boards(state, max_actions: int = 2) -> dict[tuple, list[int]]:
    """``{resting board: action sequence}`` for every legal turn from ``state``.

    ``state`` is a :class:`~raccoon.env.game_wrapper.GameState` at one of the
    mover's decisions. OpenSpiel splits a doubles roll into two consecutive
    decisions by the same player, so a turn can need two actions; this walks
    both and keys the result by the board the turn comes to rest on, in the
    mover's own frame (``[opponent, mover]``, matching
    :func:`~raccoon.eval.gnubg_adapter.board_from_view` before the move).

    Terminal outcomes are keyed by the board too, so a bear-off that ends the
    game is matchable like any other play.
    """
    from raccoon.eval.gnubg_adapter import board_from_view

    me = state.current_player()
    out: dict[tuple, list[int]] = {}

    def walk(node, prefix: list[int], depth: int) -> None:
        for action in node.legal_actions():
            child = node.clone()
            child.apply_action(action)
            seq = prefix + [action]
            if not child.is_terminal() and child.current_player() == me and depth < max_actions:
                walk(child, seq, depth + 1)
                continue
            # Name the perspective rather than relying on "current player":
            # after a turn the state is a chance node (player -1) and after a
            # bear-off it is terminal, and neither is a seat index. Reading it
            # from `me` also puts the board straight into the mover's own frame,
            # which is the frame a pre-move target board is in.
            board = board_from_view(child.board_from_perspective(me))
            out.setdefault((tuple(board[0]), tuple(board[1])), seq)

    walk(state, [], 1)
    return out


def actions_reaching(state, target: list[list[int]]) -> list[int]:
    """The OpenSpiel action sequence whose turn ends on ``target``.

    Raises :class:`GnubgProtocolError` when no legal turn reaches it. That is the
    point: it converts a notation-parsing mistake into a loud failure on the very
    next position, rather than into an engine that quietly plays something else
    for a whole run.
    """
    key = (tuple(target[0]), tuple(target[1]))
    found = resting_boards(state).get(key)
    if found is None:
        raise GnubgProtocolError(
            "no legal turn reaches the board GNUBG's move implies; "
            "the notation parse and the position have diverged"
        )
    return found
